const mongoose = require("mongoose");

const securityAlertSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      trim: true,
    },
    role: {
      type: String,
      required: true,
      trim: true,
    },
    subRole: {
      type: String,
      required: true,
      trim: true,
    },
    email: {
      type: String,
      required: true,
      lowercase: true,
      trim: true,
    },
    phoneNumber: {
      type: String,
      required: true,
      trim: true,
    },
  },
  {
    collection: "security_alerts",
    timestamps: true,
  }
);

module.exports = mongoose.model("SecurityAlert", securityAlertSchema);
